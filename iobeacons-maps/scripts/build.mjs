// Builds the browser app: copies MapLibre into public/vendor, writes the static
// catalog used by shared maps, and bundles client/ into public/app.js.
import { build } from 'esbuild';
import { cp, mkdir, writeFile, readdir, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => path.join(root, ...p);

// 1. MapLibre (ESM build plus its worker), served as-is.
const mlDist = r('node_modules/maplibre-gl/dist');
const vendor = r('public/vendor/maplibre');
await mkdir(vendor, { recursive: true });
for (const f of await readdir(mlDist)) {
  if (/-dev\.|\.d\.ts$/.test(f)) continue;
  await cp(path.join(mlDist, f), path.join(vendor, f));
}

// 2. Catalog tile info for shared maps (no sign-in, so no /catalog call).
process.env.OFFLINE ??= '1';
const { CATALOG } = await import(r('src/services/catalog.js'));
const pick = ({ key, name, category, type, tiles, tileSize, minzoom, maxzoom, opacity, refreshSec, attribution }) => ({ key, name, category, type, tiles, tileSize, minzoom, maxzoom, opacity, refreshSec, attribution });
await writeFile(r('client/catalog-static.js'), `// Generated by scripts/build.mjs. Do not edit.\nexport const CATALOG_STATIC = ${JSON.stringify(CATALOG.map(pick), null, 1)};\n`);

// 3. The app bundle.
const dev = process.argv.includes('--dev');
await build({
  entryPoints: [r('client/main.js')],
  outfile: r('public/app.js'),
  bundle: true, format: 'esm', target: ['es2022'], platform: 'browser',
  external: ['maplibre-gl'],
  minify: !dev, sourcemap: true, legalComments: 'none', logLevel: 'info',
});
// 4. Version the bundle and stylesheet in the HTML so browsers never keep an old copy.
const ver = async (f) => createHash('sha1').update(await readFile(r('public', f))).digest('hex').slice(0, 10);
const v = { 'app.js': await ver('app.js'), 'app.css': await ver('app.css') };
for (const page of ['index.html', 'embed.html']) {
  let html = await readFile(r('public', page), 'utf8');
  for (const [f, hash] of Object.entries(v)) html = html.replace(new RegExp(`(["'/])${f.replace('.', '\\.')}(\\?v=[0-9a-f]+)?(["'])`, 'g'), `$1${f}?v=${hash}$3`);
  await writeFile(r('public', page), html);
}
console.log('build ok');
process.exit(0);
